def wrap_figures(html: str, label: str) -> str:
    """Posa els src absoluts i numera els peus de figura que genera pandoc."""
    html = re.sub(r'<img src="(/[^"]+)" alt="([^"]*)"([^>]*)>',
                  lambda m: '<img src="' + static_url(m.group(1)) + '" alt="'
                            + m.group(2) + '"' + m.group(3) + '>', html)
    n = [0]

    def repl(m):
        n[0] += 1
        return ('<figcaption><span class="fig-n">%s %d</span>%s</figcaption>'
                % (label, n[0], m.group(1)))

    return re.sub(r"<figcaption[^>]*>(.*?)</figcaption>", repl, html, flags=re.S)


def number_sections(html: str):
    """Numera els h2, els dona id i retorna la llista per al sumari."""
    toc = []

    def repl(m):
        n = len(toc) + 1
        title = m.group(1)
        sid = "sec-%d" % n
        toc.append((sid, title))
        return '<h2 id="' + sid + '"><span class="secnum">' + str(n) + '</span>' + \
               title + '</h2>'

    return re.sub(r"<h2[^>]*>(.*?)</h2>", repl, html, flags=re.S), toc


