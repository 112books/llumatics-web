def read_frontmatter(path: Path):
    """Retorna (frontmatter YAML, cos Markdown) d'un fitxer de contingut."""
    raw = path.read_text(encoding="utf-8")
    if not raw.startswith("---"):
        return {}, raw
    _, fm, body = raw.split("---", 2)
    return yaml.safe_load(fm) or {}, body


def markdown_to_html(md: str) -> str:
    """Markdown -> fragment HTML amb pandoc (sense smartypants per no tocar el text)."""
    pandoc = shutil.which("pandoc")
    if not pandoc:
        sys.exit("Cal pandoc al PATH (brew install pandoc).")
    out = subprocess.run(
        [pandoc, "-f", "markdown-smart", "-t", "html", "--wrap=none"],
        input=md, capture_output=True, text=True, check=True,
    )
    return out.stdout


def static_url(path: str) -> str:
    """Converteix /images/... en file:// absolut."""
    return (STATIC / path.lstrip("/")).resolve().as_uri()


